CREATE SCHEMA IF NOT EXISTS cybermanager;

CREATE TABLE IF NOT EXISTS cybermanager.cm_users (
    id UUID NOT NULL,
    email VARCHAR(255) NOT NULL,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    CONSTRAINT pk_cm_users PRIMARY KEY (id),
    CONSTRAINT uk_cm_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS cybermanager.cm_user_roles (
    user_id UUID NOT NULL,
    role VARCHAR(255),
    CONSTRAINT fk_cm_user_roles_user
        FOREIGN KEY (user_id) REFERENCES cybermanager.cm_users (id)
);

CREATE TABLE IF NOT EXISTS cybermanager.cm_products (
    id UUID NOT NULL,
    name VARCHAR(255),
    price NUMERIC(38, 2),
    category VARCHAR(255),
    description VARCHAR(255),
    status VARCHAR(255),
    CONSTRAINT pk_cm_products PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS cybermanager.cm_subscription_offers (
    id UUID NOT NULL,
    name VARCHAR(255),
    price NUMERIC(38, 2),
    included_minutes INTEGER NOT NULL,
    status VARCHAR(255),
    CONSTRAINT pk_cm_subscription_offers PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS cybermanager.cm_customers (
    id UUID NOT NULL,
    name VARCHAR(255),
    type VARCHAR(255),
    status VARCHAR(255),
    remaining_minutes INTEGER NOT NULL,
    CONSTRAINT pk_cm_customers PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_cm_customers_name
    ON cybermanager.cm_customers (name);
CREATE INDEX IF NOT EXISTS idx_cm_customers_type_name
    ON cybermanager.cm_customers (type, name);

CREATE TABLE IF NOT EXISTS cybermanager.cm_customer_debts (
    id UUID NOT NULL,
    customer_id UUID,
    label VARCHAR(255),
    comment VARCHAR(255),
    amount NUMERIC(38, 2),
    status VARCHAR(255),
    created_at TIMESTAMP(6),
    settled_at TIMESTAMP(6),
    CONSTRAINT pk_cm_customer_debts PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_cm_customer_debts_customer_created_at
    ON cybermanager.cm_customer_debts (customer_id, created_at);
CREATE INDEX IF NOT EXISTS idx_cm_customer_debts_status
    ON cybermanager.cm_customer_debts (status);

CREATE TABLE IF NOT EXISTS cybermanager.cm_generated_archive_files (
    id UUID NOT NULL,
    file_name VARCHAR(255),
    file_type VARCHAR(255),
    generated_by VARCHAR(255),
    generated_at TIMESTAMP(6),
    CONSTRAINT pk_cm_generated_archive_files PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_cm_generated_archive_files_generated_at
    ON cybermanager.cm_generated_archive_files (generated_at);

CREATE TABLE IF NOT EXISTS cybermanager.cm_company_profile (
    id UUID NOT NULL,
    legal_name VARCHAR(255),
    siret VARCHAR(255),
    phone VARCHAR(255),
    email VARCHAR(255),
    address_line1 VARCHAR(255),
    address_line2 VARCHAR(255),
    postal_code VARCHAR(255),
    city VARCHAR(255),
    country VARCHAR(255),
    updated_at TIMESTAMP(6),
    CONSTRAINT pk_cm_company_profile PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS cybermanager.cm_connection_pricing_tier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    duration_minutes INTEGER NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    CONSTRAINT pk_cm_connection_pricing_tier PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS cybermanager.cm_sessions (
    id UUID NOT NULL,
    customer_id UUID,
    workstation VARCHAR(255),
    started_at TIMESTAMP(6),
    ended_at TIMESTAMP(6),
    paused_at TIMESTAMP(6),
    paid BOOLEAN,
    paused_minutes INTEGER,
    paused_seconds INTEGER,
    consumed_minutes INTEGER,
    consumed_seconds INTEGER,
    calculated_price NUMERIC(38, 2),
    CONSTRAINT pk_cm_sessions PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_cm_sessions_customer_started_at
    ON cybermanager.cm_sessions (customer_id, started_at);
CREATE INDEX IF NOT EXISTS idx_cm_sessions_customer_ended_at
    ON cybermanager.cm_sessions (customer_id, ended_at);
CREATE INDEX IF NOT EXISTS idx_cm_sessions_paid
    ON cybermanager.cm_sessions (paid);

CREATE TABLE IF NOT EXISTS cybermanager.cm_sales (
    id UUID NOT NULL,
    customer_id UUID,
    session_id UUID,
    type VARCHAR(255),
    sold_at TIMESTAMP(6),
    total_amount NUMERIC(38, 2),
    CONSTRAINT pk_cm_sales PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_cm_sales_customer_sold_at
    ON cybermanager.cm_sales (customer_id, sold_at);
CREATE INDEX IF NOT EXISTS idx_cm_sales_session_id
    ON cybermanager.cm_sales (session_id);

CREATE TABLE IF NOT EXISTS cybermanager.cm_sale_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    sale_id UUID,
    label VARCHAR(255),
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(38, 2),
    total_price NUMERIC(38, 2),
    CONSTRAINT pk_cm_sale_lines PRIMARY KEY (id),
    CONSTRAINT fk_cm_sale_lines_sale
        FOREIGN KEY (sale_id) REFERENCES cybermanager.cm_sales (id)
);

CREATE TABLE IF NOT EXISTS cybermanager.cm_invoices (
    id UUID NOT NULL,
    sale_id UUID,
    customer_id UUID,
    invoice_number VARCHAR(255),
    customer_name VARCHAR(255),
    issued_at TIMESTAMP(6),
    status VARCHAR(255),
    total_amount NUMERIC(38, 2),
    CONSTRAINT pk_cm_invoices PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_cm_invoices_number
    ON cybermanager.cm_invoices (invoice_number);
CREATE INDEX IF NOT EXISTS idx_cm_invoices_customer_issued_at
    ON cybermanager.cm_invoices (customer_name, issued_at);
CREATE INDEX IF NOT EXISTS idx_cm_invoices_status_issued_at
    ON cybermanager.cm_invoices (status, issued_at);

CREATE TABLE IF NOT EXISTS cybermanager.cm_invoice_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    invoice_id UUID NOT NULL,
    label VARCHAR(255),
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(38, 2),
    total_price NUMERIC(38, 2),
    CONSTRAINT pk_cm_invoice_lines PRIMARY KEY (id),
    CONSTRAINT fk_cm_invoice_lines_invoice
        FOREIGN KEY (invoice_id) REFERENCES cybermanager.cm_invoices (id)
);
