DO $$
BEGIN
    IF to_regclass('cybermanager.cm_connection_pricing_tier') IS NOT NULL
       AND to_regclass('cybermanager.cm_connection_pricing_tiers') IS NULL THEN
        ALTER TABLE cybermanager.cm_connection_pricing_tier
            RENAME TO cm_connection_pricing_tiers;
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS cybermanager.cm_connection_pricing_grids (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_cm_connection_pricing_grids PRIMARY KEY (id)
);

ALTER TABLE cybermanager.cm_connection_pricing_tiers
    ADD COLUMN IF NOT EXISTS grid_id BIGINT;

DO $$
DECLARE
    migrated_grid_id BIGINT;
BEGIN
    IF EXISTS (SELECT 1 FROM cybermanager.cm_connection_pricing_tiers)
       AND NOT EXISTS (SELECT 1 FROM cybermanager.cm_connection_pricing_grids WHERE active) THEN
        INSERT INTO cybermanager.cm_connection_pricing_grids (active, created_at, updated_at)
        VALUES (TRUE, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
        RETURNING id INTO migrated_grid_id;

        UPDATE cybermanager.cm_connection_pricing_tiers
        SET grid_id = migrated_grid_id
        WHERE grid_id IS NULL;
    END IF;
END
$$;

ALTER TABLE cybermanager.cm_connection_pricing_tiers
    ALTER COLUMN grid_id SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_cm_connection_pricing_tiers_grid'
          AND conrelid = 'cybermanager.cm_connection_pricing_tiers'::regclass
    ) THEN
        ALTER TABLE cybermanager.cm_connection_pricing_tiers
            ADD CONSTRAINT fk_cm_connection_pricing_tiers_grid
            FOREIGN KEY (grid_id) REFERENCES cybermanager.cm_connection_pricing_grids (id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'uk_cm_connection_pricing_tiers_grid_duration'
          AND conrelid = 'cybermanager.cm_connection_pricing_tiers'::regclass
    ) THEN
        ALTER TABLE cybermanager.cm_connection_pricing_tiers
            ADD CONSTRAINT uk_cm_connection_pricing_tiers_grid_duration
            UNIQUE (grid_id, duration_minutes);
    END IF;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS uk_cm_connection_pricing_grids_active
    ON cybermanager.cm_connection_pricing_grids (active)
    WHERE active = TRUE;
